-- Función trigger para actualización automática de fecha_actualizacion
CREATE OR REPLACE FUNCTION public.set_fecha_actualizacion()
RETURNS TRIGGER AS $$
BEGIN
    NEW.fecha_actualizacion = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- ---------------------------------------------------------------------
-- 1. Tabla: usuarios
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.usuarios (
    id_usuario BIGSERIAL PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    email VARCHAR(150) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    telefono VARCHAR(20),
    cod_empleado VARCHAR(20) UNIQUE,
    rol VARCHAR(20) NOT NULL,
    id_admin_supervisor BIGINT,
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    creado_en TIMESTAMP,
    CONSTRAINT usuarios_rol_check CHECK (rol IN ('ADMINISTRADOR', 'SUPERVISOR', 'CONDUCTOR', 'OPERADOR'))
);

ALTER TABLE public.usuarios
    DROP CONSTRAINT IF EXISTS usuarios_id_admin_supervisor_fkey,
    ADD CONSTRAINT usuarios_id_admin_supervisor_fkey 
    FOREIGN KEY (id_admin_supervisor) REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL;

DROP TRIGGER IF EXISTS trg_usuarios_upd ON public.usuarios;
CREATE TRIGGER trg_usuarios_upd
    BEFORE UPDATE ON public.usuarios
    FOR EACH ROW EXECUTE FUNCTION public.set_fecha_actualizacion();

-- ---------------------------------------------------------------------
-- 2. Tabla: clientes
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.clientes (
    id_cliente BIGSERIAL PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    tipo_documento VARCHAR(4) NOT NULL,
    numero_documento VARCHAR(15) NOT NULL UNIQUE,
    direccion_fiscal VARCHAR(255),
    contacto_nombre VARCHAR(150),
    telefono VARCHAR(20),
    email VARCHAR(150),
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_actualizacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT clientes_tipo_documento_check CHECK (tipo_documento IN ('DNI', 'RUC'))
);

DROP TRIGGER IF EXISTS trg_clientes_upd ON public.clientes;
CREATE TRIGGER trg_clientes_upd
    BEFORE UPDATE ON public.clientes
    FOR EACH ROW EXECUTE FUNCTION public.set_fecha_actualizacion();

-- ---------------------------------------------------------------------
-- 3. Tabla: flota
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.flota (
    id_flota BIGSERIAL PRIMARY KEY,
    nombre_flota VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
-- 4. Tabla: vehiculos
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.vehiculos (
    id_vehiculo BIGSERIAL PRIMARY KEY,
    id_flota BIGINT,
    placa VARCHAR(10) NOT NULL UNIQUE,
    tipo_camion VARCHAR(50),
    capacidad_max_ton NUMERIC(6,2) NOT NULL,
    volumen_max_m3 NUMERIC(6,2),
    estado_operativo VARCHAR(20) DEFAULT 'DISPONIBLE' NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    modelo VARCHAR(100),
    peso_max_eje_toneladas DOUBLE PRECISION,
    conductor_id BIGINT,
    CONSTRAINT vehiculos_capacidad_max_ton_check CHECK (capacidad_max_ton > 0),
    CONSTRAINT vehiculos_volumen_max_m3_check CHECK (volumen_max_m3 > 0),
    CONSTRAINT vehiculos_estado_operativo_check CHECK (estado_operativo IN ('DISPONIBLE', 'EN_RUTA', 'MANTENIMIENTO', 'INACTIVO')),
    CONSTRAINT vehiculos_id_flota_fkey FOREIGN KEY (id_flota) REFERENCES public.flota(id_flota) ON DELETE SET NULL,
    CONSTRAINT vehiculos_conductor_id_fkey FOREIGN KEY (conductor_id) REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL
);

-- ---------------------------------------------------------------------
-- 5. Tabla: transportistas
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.transportistas (
    id_transportista BIGSERIAL PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    dni VARCHAR(8) NOT NULL UNIQUE,
    licencia_conducir VARCHAR(20) NOT NULL UNIQUE,
    categoria_licencia VARCHAR(10),
    telefono VARCHAR(20),
    activo BOOLEAN DEFAULT TRUE NOT NULL,
    fecha_creacion TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- ---------------------------------------------------------------------
-- 6. Tabla: asignaciones_conduccion
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.asignaciones_conduccion (
    id_asignacion BIGSERIAL PRIMARY KEY,
    id_vehiculo BIGINT NOT NULL,
    id_transportista BIGINT NOT NULL,
    fecha_inicio TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_fin TIMESTAMP,
    estado VARCHAR(15) DEFAULT 'ACTIVA' NOT NULL,
    CONSTRAINT asignaciones_conduccion_estado_check CHECK (estado IN ('ACTIVA', 'FINALIZADA')),
    CONSTRAINT asignaciones_conduccion_id_vehiculo_fkey FOREIGN KEY (id_vehiculo) REFERENCES public.vehiculos(id_vehiculo) ON DELETE CASCADE,
    CONSTRAINT asignaciones_conduccion_id_transportista_fkey FOREIGN KEY (id_transportista) REFERENCES public.transportistas(id_transportista) ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- 7. Tabla: rutas
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.rutas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    algoritmo_usado VARCHAR(50),
    costo_estimado_soles DOUBLE PRECISION,
    creado_en TIMESTAMP,
    distancia_total_km DOUBLE PRECISION,
    estado VARCHAR(20) NOT NULL,
    fecha_ruta DATE NOT NULL,
    tiempo_estimado_min INTEGER,
    creado_por_id BIGINT,
    vehiculo_id BIGINT NOT NULL,
    CONSTRAINT rutas_estado_check CHECK (estado IN ('PLANIFICADA', 'EN_EJECUCION', 'COMPLETADA', 'CANCELADA')),
    CONSTRAINT rutas_creado_por_id_fkey FOREIGN KEY (creado_por_id) REFERENCES public.usuarios(id_usuario) ON DELETE SET NULL,
    CONSTRAINT rutas_vehiculo_id_fkey FOREIGN KEY (vehiculo_id) REFERENCES public.vehiculos(id_vehiculo) ON DELETE RESTRICT
);

-- ---------------------------------------------------------------------
-- 8. Tabla: pedidos
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.pedidos (
    id_pedido BIGSERIAL PRIMARY KEY,
    id_cliente BIGINT NOT NULL,
    id_usuario_gestor BIGINT NOT NULL,
    tipo_material VARCHAR(100) NOT NULL,
    peso_t NUMERIC(6,2) NOT NULL,
    volumen_m3 NUMERIC(6,2),
    direccion_destino VARCHAR(255) NOT NULL,
    prioridad VARCHAR(10) DEFAULT 'MEDIA' NOT NULL,
    objetivo_optimizacion VARCHAR(20) DEFAULT 'EQUILIBRIO' NOT NULL,
    evitar_trafico_pesado BOOLEAN DEFAULT FALSE NOT NULL,
    evitar_zonas_mantenimiento BOOLEAN DEFAULT FALSE NOT NULL,
    fecha_emision TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    fecha_entrega TIMESTAMP,
    estado_pedido VARCHAR(20) DEFAULT 'REGISTRADO' NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    creado_en TIMESTAMP,
    ventana_fin TIMESTAMP,
    ventana_inicio TIMESTAMP,
    ruta_id BIGINT,
    CONSTRAINT pedidos_peso_t_check CHECK (peso_t > 0),
    CONSTRAINT pedidos_volumen_m3_check CHECK (volumen_m3 > 0),
    CONSTRAINT pedidos_prioridad_check CHECK (prioridad IN ('ALTA', 'MEDIA', 'BAJA')),
    CONSTRAINT pedidos_objetivo_optimizacion_check CHECK (objetivo_optimizacion IN ('MENOR_TIEMPO', 'MENOR_COSTO', 'EQUILIBRIO')),
    CONSTRAINT pedidos_estado_pedido_check CHECK (estado_pedido IN ('REGISTRADO', 'EN_PROCESO', 'OPTIMIZADO', 'DESPACHADO', 'ENTREGADO', 'CANCELADO')),
    CONSTRAINT pedidos_id_cliente_fkey FOREIGN KEY (id_cliente) REFERENCES public.clientes(id_cliente) ON DELETE RESTRICT,
    CONSTRAINT pedidos_id_usuario_gestor_fkey FOREIGN KEY (id_usuario_gestor) REFERENCES public.usuarios(id_usuario) ON DELETE RESTRICT,
    CONSTRAINT pedidos_ruta_id_fkey FOREIGN KEY (ruta_id) REFERENCES public.rutas(id) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_pedidos_estado ON public.pedidos(estado_pedido);

-- ---------------------------------------------------------------------
-- 9. Tabla: rutas_optimizadas
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.rutas_optimizadas (
    id_ruta BIGSERIAL PRIMARY KEY,
    id_pedido BIGINT NOT NULL,
    id_vehiculo BIGINT,
    id_transportista BIGINT,
    origen VARCHAR(255) NOT NULL,
    destino VARCHAR(255) NOT NULL,
    secuencia_paradas TEXT,
    distancia_km NUMERIC(8,2),
    tiempo_estimado_min NUMERIC(8,2),
    costo_operativo NUMERIC(10,2),
    algoritmo_utilizado VARCHAR(50),
    puntaje NUMERIC(5,2),
    estado_ruta VARCHAR(20) DEFAULT 'ALTERNATIVA' NOT NULL,
    fecha_calculo TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT rutas_optimizadas_estado_ruta_check CHECK (estado_ruta IN ('OPTIMA', 'ALTERNATIVA', 'NO_RECOMENDADA')),
    CONSTRAINT rutas_optimizadas_id_pedido_fkey FOREIGN KEY (id_pedido) REFERENCES public.pedidos(id_pedido) ON DELETE CASCADE,
    CONSTRAINT rutas_optimizadas_id_vehiculo_fkey FOREIGN KEY (id_vehiculo) REFERENCES public.vehiculos(id_vehiculo) ON DELETE SET NULL,
    CONSTRAINT rutas_optimizadas_id_transportista_fkey FOREIGN KEY (id_transportista) REFERENCES public.transportistas(id_transportista) ON DELETE SET NULL
);

CREATE INDEX IF NOT EXISTS idx_rutas_opt_estado ON public.rutas_optimizadas(estado_ruta);
CREATE INDEX IF NOT EXISTS idx_rutas_opt_pedido ON public.rutas_optimizadas(id_pedido);
